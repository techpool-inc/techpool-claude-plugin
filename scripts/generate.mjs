#!/usr/bin/env node
// Generates plugins/techpool/ from the Techpool MCP server's own sources, so the
// plugin can never drift from the tools the server registers.
//
//   node scripts/generate.mjs --source <techpool-server>/mcp          write
//   node scripts/generate.mjs --source <techpool-server>/mcp --check  exit 1 if stale
//   node scripts/generate.mjs --source <...>/mcp --zip dist/techpool.zip  also zip the plugin
//
// Inputs (read-only): <source>/catalog/tools.json (generated from the registered
// tools, checked by techpool-server CI) and <source>/skill/techpool/** (the
// authored companion skill, checked against that catalog by techpool-server CI).
// Output: plugins/techpool/{.claude-plugin/plugin.json,.mcp.json,skills/techpool/**}.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'plugins', 'techpool');
const SERVER_URL = 'https://mcp.techpool.tech/mcp';
const GENERATED = 'GENERATED by scripts/generate.mjs from techpool-server mcp/. Do not edit.';

function fail(message) {
  console.error(`generate: ${message}`);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const source = arg('--source');
const check = process.argv.includes('--check');
const zipTo = arg('--zip');
if (!source) {
  fail('--source <techpool-server>/mcp is required');
}
const catalogPath = path.join(source, 'catalog', 'tools.json');
const skillSrc = path.join(source, 'skill', 'techpool');
for (const p of [catalogPath, path.join(skillSrc, 'SKILL.md')]) {
  if (!fs.existsSync(p)) {
    fail(`missing input: ${p}`);
  }
}

const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
const { toolCount, catalogHash, tools } = catalog;
if (typeof toolCount !== 'number' || typeof catalogHash !== 'string' || !Array.isArray(tools)) {
  fail('tools.json lacks toolCount/catalogHash/tools');
}

// Every generated file, as relative path -> content.
const files = new Map();

function walk(dir, rel = '') {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const from = path.join(dir, entry.name);
    const to = path.join(rel, entry.name);
    if (entry.isDirectory()) {
      walk(from, to);
    } else if (entry.isFile()) {
      files.set(path.join('skills', 'techpool', to), fs.readFileSync(from, 'utf8'));
    }
  }
}
walk(skillSrc);

// Stamp the copied SKILL.md (never the authored one) with what it was checked against.
const skillKey = path.join('skills', 'techpool', 'SKILL.md');
const skillLines = files.get(skillKey).split('\n');
const metaIdx = skillLines.findIndex((l) => /^metadata:\s*$/.test(l));
if (metaIdx < 0) {
  fail('SKILL.md frontmatter has no metadata: block');
}
skillLines.splice(metaIdx + 1, 0,
  `  tool_count: "${toolCount}"`,
  `  catalog_hash: "${catalogHash}"`,
  `  server_url: "${SERVER_URL}"`);
let skill = skillLines.join('\n');
skill = skill.replace('\nRead only the reference file for the job in front of you.',
  '\nRead only the reference file for the job in front of you. Every tool, with its access and permission, is listed in [references/tool-catalog.md](references/tool-catalog.md).');
files.set(skillKey, skill);

// The full tool list, rendered from the catalog.
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const firstSentence = (s) => esc(s).split(/(?<=\.)\s/)[0];
const rows = [...tools].sort((a, b) => a.name.localeCompare(b.name)).map((t) => {
  const flags = [t.destructive ? 'destructive' : '', t.twoPhase ? 'two-phase' : ''].filter(Boolean).join(', ');
  return `| \`${t.name}\` | ${esc(t.access)} | ${esc(t.scope) || '-'} | ${flags || '-'} | ${firstSentence(t.description)} |`;
});
files.set(path.join('skills', 'techpool', 'references', 'tool-catalog.md'), [
  `<!-- ${GENERATED} -->`,
  '# Techpool tool catalog',
  '',
  `${toolCount} tools on \`${SERVER_URL}\` (catalog \`${catalogHash}\`). The connected server's own tool list always wins over this file.`,
  '',
  'Two-phase tools return a preview first and change nothing until the user says yes (see SKILL.md rule 2).',
  '',
  '| Tool | Access | Permission | Flags | What it does |',
  '|---|---|---|---|---|',
  ...rows,
  '',
].join('\n'));

files.set(path.join('.claude-plugin', 'plugin.json'), JSON.stringify({
  name: 'techpool',
  version: `1.0.0+${catalogHash}`,
  description: 'Techpool field service operations in Claude: missions, schedules, field work reports, timesheets, expenses, invoices and clients, through the Techpool MCP connector. Your admin installs it once; every tech has it.',
  author: { name: 'Techpool', url: 'https://techpool.tech' },
  homepage: 'https://techpool.tech/mcp',
  repository: 'https://git.no-cows.com/techpool/techpool-claude-plugin',
  license: 'MIT',
  keywords: ['field-service', 'techpool', 'mcp', 'field-work-reports', 'timesheets', 'scheduling'],
}, null, 2) + '\n');

files.set('.mcp.json', JSON.stringify({
  mcpServers: { techpool: { type: 'http', url: SERVER_URL } },
}, null, 2) + '\n');

function listExisting(dir, rel = '') {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) {
      out.push(...listExisting(path.join(dir, e.name), r));
    } else {
      out.push(r);
    }
  }
  return out;
}

if (check) {
  const stale = [];
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== content) {
      stale.push(rel);
    }
  }
  for (const rel of listExisting(OUT)) {
    if (!files.has(rel)) {
      stale.push(`${rel} (not generated)`);
    }
  }
  if (stale.length) {
    console.error(`plugin is stale against catalog ${catalogHash}:\n  ${stale.join('\n  ')}`);
    console.error('Run: node scripts/generate.mjs --source <techpool-server>/mcp  and commit.');
    process.exit(1);
  }
  console.log(`plugin is current (${toolCount} tools, catalog ${catalogHash})`);
} else {
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  console.log(`wrote ${files.size} files (${toolCount} tools, catalog ${catalogHash})`);
}

if (zipTo) {
  const dest = path.resolve(zipTo);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.rmSync(dest, { force: true });
  execFileSync('zip', ['-qrX', dest, '.'], { cwd: OUT });
  console.log(`zipped ${dest}`);
}
